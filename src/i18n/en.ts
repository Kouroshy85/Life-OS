import { formatClock, formatDuration, formatShortDate } from "../domain/time";
import type { DeadlineNote, Part, Trigger } from "../domain/explain";
import type { Energy, Priority } from "../domain/types";

const plural = (n: number, one: string, many = `${one}s`) => `${n} ${n === 1 ? one : many}`;

const triggerText = (x: Trigger): string => {
  if (typeof x === "string") return x;
  switch (x.t) {
    case "overrun":
      return `“${x.title}” ran ${formatDuration(x.dur)} over`;
    case "added":
      return `“${x.title}” was added at ${formatClock(x.at)}`;
    case "changed":
      return `“${x.title}” changed at ${formatClock(x.at)}`;
    case "manual":
      return "you asked to recalculate the rest of the day";
  }
};

const deadlineText = (d: DeadlineNote): string => {
  const at = "at" in d && d.at != null ? ` at ${formatClock(d.at)}` : "";
  switch (d.kind) {
    case "overdue":
      return `deadline passed on ${formatShortDate(d.date)}`;
    case "today":
      return `due today${at}`;
    case "thatDay":
      return `due that day${at}`;
    case "tomorrow":
      return `due tomorrow${at}`;
    case "inDays":
      return `due in ${d.n} days`;
  }
};

const PRIORITY_WORD: Record<Priority, string> = {
  1: "Low priority",
  2: "Medium priority",
  3: "High priority",
  4: "Critical priority",
};

function part(p: Part): string {
  switch (p.k) {
    case "base": {
      const bits: string[] = [];
      if (p.priority) bits.push(PRIORITY_WORD[p.priority]);
      if (p.deadline) bits.push(deadlineText(p.deadline));
      if (p.inProgress) bits.push("already in progress");
      const head = bits.join(", ");
      const rank = p.rank === 0 ? "first in the day's order" : `#${p.rank + 1} in the day's order`;
      return `${head[0].toUpperCase()}${head.slice(1)} — ${rank}.`;
    }
    case "placeFocus":
      return "Placed in your focus hours because it needs deep focus.";
    case "placeOutsideFocus":
      return "Kept outside your focus hours since it needs little energy.";
    case "placeFocusFull":
      return "Focus hours were full, so it takes the earliest open slot.";
    case "placeOnlyFocus":
      return "Only open slot was inside your focus hours.";
    case "placeEarliest":
      return "Earliest open slot that fits.";
    case "moved":
      return `Moved from ${formatClock(p.from)} to ${formatClock(p.to)}${p.trigger ? ` because ${triggerText(p.trigger)}` : ""}.`;
    case "late":
      return `Warning: ends after its ${p.at != null ? `${formatClock(p.at)} ` : ""}deadline — consider trimming the scope.`;
    case "session":
      return `Session ${p.i} of ${p.n} — no single gap fits ${formatDuration(p.dur)}.`;
    case "shortSession":
      return `Only a ${formatDuration(p.dur)} session fits on this day.`;
    case "breakReason":
      return `Short break — you would otherwise work more than ${formatDuration(p.after)} without a pause.`;
    case "skippedToday":
      return "You skipped this today, so it stays in the backlog.";
    case "noHours":
      return "Working hours are empty — set a start and end time in Planner settings.";
    case "dayPassed":
      return "This day has already passed.";
    case "hoursEnded":
      return `Your working hours ended at ${formatClock(p.end)}. Plan tomorrow instead.`;
    case "partly":
      return `Partly scheduled: ${formatDuration(p.placed)} on this day, ${formatDuration(p.rest)} still needs a slot.`;
    case "noFree":
      return `No free time is left on this day; it needs ${formatDuration(p.need)}.`;
    case "notEnough":
      return `Needs ${formatDuration(p.need)}, but only ${formatDuration(p.free)} of free time remains.`;
    case "breakEats":
      return `Needs ${formatDuration(p.need)}. The longest free gap is ${formatDuration(p.longest)}, but a required break leaves too little of it.`;
    case "gapShort":
      return `Needs ${formatDuration(p.need)}, but the longest free gap is ${formatDuration(p.longest)} and it can't be split into sessions of ${formatDuration(p.min)} or more.`;
    case "overdueSuffix":
      return "Its deadline has already passed.";
    case "dueDaySuffix":
      return "It is due that day — free up time or extend your hours.";
    case "toBacklog":
      return `Moved to the backlog because ${triggerText(p.trigger)}.`;
    case "byYouSlot":
      return "Scheduled by you into the earliest free slot.";
    case "movedByYou":
      return `Moved by you to ${formatClock(p.at)}. The planner will keep it here.`;
    case "resizedByYou":
      return `Resized by you to ${formatDuration(p.dur)}. The planner will keep it here.`;
    case "proposal":
      return `${plural(p.sessions, "session")} · ${formatDuration(p.scheduled)} of ${formatDuration(p.available)} free time used${p.backlog ? ` · ${p.backlog} left in backlog` : ""}`;
  }
}

