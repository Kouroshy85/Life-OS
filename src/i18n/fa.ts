/*
 * Voice: how you'd explain the app to a friend. Spoken forms ("می‌خوای", "رو", "شه"),
 * short sentences, no "لطفاً" or "می‌باشد". "ددلاین" and "بک‌لاگ"-style loanwords are
 * fine where people actually say them; the backlog is just "کارای منتظر".
 */

const triggerText = (x: Trigger): string => {
  if (typeof x === "string") return x;
  switch (x.t) {
    case "overrun":
      return `«${x.title}» ${formatDuration(x.dur)} بیشتر طول کشید`;
    case "added":
      return `«${x.title}» ساعت ${formatClock(x.at)} اضافه شد`;
    case "changed":
      return `«${x.title}» عوض شد و افتاد ساعت ${formatClock(x.at)}`;
    case "manual":
      return "خودت گفتی بقیه‌ی روز رو دوباره بچینم";
  }
};

const deadlineText = (d: DeadlineNote): string => {
  const at = "at" in d && d.at != null ? ` تا ساعت ${formatClock(d.at)}` : "";
  switch (d.kind) {
    case "overdue":
      return `ددلاینش ${formatShortDate(d.date)} بود و گذشته`;
    case "today":
      return `باید امروز${at} تموم شه`;
    case "thatDay":
      return `باید همون روز${at} تموم شه`;
    case "tomorrow":
      return `باید فردا${at} تموم شه`;
    case "inDays":
      return `${num(d.n)} روز دیگه ددلاینشه`;
  }
};

const PRIORITY_WORD: Record<Priority, string> = {
  1: "اولویتش کمه",
  2: "اولویتش معمولیه",
  3: "اولویتش بالاست",
  4: "خیلی مهمه",
};

function part(p: Part): string {
  switch (p.k) {
    case "base": {
      const bits: string[] = [];
      if (p.priority) bits.push(PRIORITY_WORD[p.priority]);
      if (p.deadline) bits.push(deadlineText(p.deadline));
      if (p.inProgress) bits.push("قبلاً شروعش کردی");
      const rank = p.rank === 0 ? "برای همین اول از همه اومده" : `شماره‌ی ${num(p.rank + 1)} صف این روزه`;
      return `${bits.join("، ")} — ${rank}.`;
    }
    case "placeFocus":
      return "گذاشتمش تو ساعت‌های تمرکزت، چون حسابی تمرکز می‌خواد.";
    case "placeOutsideFocus":
      return "از ساعت‌های تمرکزت دورش نگه داشتم، چون انرژی زیادی نمی‌بره.";
    case "placeFocusFull":
      return "ساعت‌های تمرکزت پر بود، برای همین رفت اولین جای خالی.";
    case "placeOnlyFocus":
      return "تنها جای خالی همین تو ساعت‌های تمرکزت بود.";
    case "placeEarliest":
      return "اولین جای خالی‌ای بود که جا می‌شد.";
    case "moved":
      return `از ${formatClock(p.from)} رفت ${formatClock(p.to)}${p.trigger ? `، چون ${triggerText(p.trigger)}` : ""}.`;
    case "late":
      return `حواست باشه: بعد از ددلاین${p.at != null ? ` ${formatClock(p.at)}` : ""} تموم می‌شه. شاید بهتر باشه یه کم جمعش کنی.`;
    case "session":
      return `جلسه‌ی ${num(p.i)} از ${num(p.n)} — ${formatDuration(p.dur)} یه‌جا هیچ‌جا جا نمی‌شد.`;
    case "shortSession":
      return `این روز فقط ${formatDuration(p.dur)} براش جا هست.`;
    case "breakReason":
      return `یه استراحت کوتاه، که بیشتر از ${formatDuration(p.after)} یه‌سره کار نکنی.`;
    case "skippedToday":
      return "امروز ردش کردی، پس فعلاً بین کارای منتظر می‌مونه.";
    case "noHours":
      return "هنوز ساعت کاری‌ات رو مشخص نکردی. از تنظیمات برنامه‌ریز شروع و پایانش رو بزن.";
    case "dayPassed":
      return "این روز دیگه گذشته.";
    case "hoursEnded":
      return `ساعت کاری‌ات ${formatClock(p.end)} تموم شد. بذارش برای فردا.`;
    case "partly":
      return `یه تیکه‌اش جا شد: ${formatDuration(p.placed)} این روز، ${formatDuration(p.rest)} دیگه هنوز جا می‌خواد.`;
    case "noFree":
      return `این روز دیگه وقت خالی نمونده و این کار ${formatDuration(p.need)} وقت می‌خواد.`;
    case "notEnough":
      return `${formatDuration(p.need)} وقت می‌خواد، ولی فقط ${formatDuration(p.free)} وقت خالی مونده.`;
    case "breakEats":
      return `${formatDuration(p.need)} وقت می‌خواد. بلندترین جای خالی ${formatDuration(p.longest)} طول داره، ولی استراحتی که لازمه ازش کم می‌کنه و دیگه جا نمی‌شه.`;
    case "gapShort":
      return `${formatDuration(p.need)} وقت می‌خواد، ولی بلندترین جای خالی ${formatDuration(p.longest)} بیشتر نیست و نمی‌شه به تیکه‌های کوچیک‌تر از ${formatDuration(p.min)} تقسیمش کرد.`;
    case "overdueSuffix":
      return "ددلاینش هم گذشته.";
    case "dueDaySuffix":
      return "همون روز هم ددلاینشه؛ یا یه کم وقت خالی کن، یا ساعت کاری‌ات رو بیشتر کن.";
    case "toBacklog":
      return `رفت بین کارای منتظر، چون ${triggerText(p.trigger)}.`;
    case "byYouSlot":
      return "خودت گذاشتیش تو اولین جای خالی.";
    case "movedByYou":
      return `خودت آوردیش ساعت ${formatClock(p.at)}. همین‌جا می‌مونه.`;
    case "resizedByYou":
      return `خودت کردیش ${formatDuration(p.dur)}. همین‌جا می‌مونه.`;
    case "proposal":
      return `${num(p.sessions)} جلسه · ${formatDuration(p.scheduled)} از ${formatDuration(p.available)} وقت خالی پر شد${p.backlog ? ` · ${num(p.backlog)} کار منتظر موند` : ""}`;
  }
}

