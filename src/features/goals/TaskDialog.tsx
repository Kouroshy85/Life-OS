import { Trash2 } from "lucide-react";
import { useEffect, useState } from "react";
import type { Energy, Priority, Task } from "../../domain/types";
import { addTask, deleteTask, updateTask, useApp, validateTaskPatch } from "../../state/store";
import { DateInput, NumberInput, TextArea, TextInput, TimeInput } from "../../ui/fields";
import { Button, Dialog, Field, Segmented, Switch } from "../../ui/primitives";

export interface TaskDraft {
  goalId?: string | null;
  milestoneId?: string | null;
  projectId?: string | null;
  inPlanner?: boolean;
}

interface Form {
  title: string;
  notes: string;
  priority: Priority;
  estimateMin: number;
  energy: Energy | "none";
  deadline: string | null;
  deadlineTime: number | null;
  inPlanner: boolean;
}

const QUICK = [15, 30, 45, 60, 90, 120];

export function TaskDialog({ open, onClose, task, draft }: { open: boolean; onClose: () => void; task?: Task | null; draft?: TaskDraft }) {
  const defaultEstimate = useApp((s) => s.prefs.defaultEstimateMin);
  const [form, setForm] = useState<Form | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    if (!open) return;
    setError(null);
    setForm(
      task
        ? {
            title: task.title,
            notes: task.notes,
            priority: task.priority,
            estimateMin: task.estimateMin,
            energy: task.energy ?? "none",
            deadline: task.deadline,
            deadlineTime: task.deadlineTime,
            inPlanner: task.inPlanner,
          }
        : {
            title: "",
            notes: "",
            priority: 2,
            estimateMin: defaultEstimate,
            energy: "none",
            deadline: null,
            deadlineTime: null,
            inPlanner: draft?.inPlanner ?? !draft?.goalId,
          },
    );
  }, [open, task, draft, defaultEstimate]);

  if (!form) return null;
  const patch = (p: Partial<Form>) => setForm((f) => (f ? { ...f, ...p } : f));

  const save = async () => {
    const values: Partial<Task> = {
      title: form.title,
      notes: form.notes,
      priority: form.priority,
      estimateMin: form.estimateMin,
      energy: form.energy === "none" ? null : form.energy,
      deadline: form.deadline,
      deadlineTime: form.deadline ? form.deadlineTime : null,
      inPlanner: form.inPlanner,
    };
    const problem = validateTaskPatch(values);
    if (problem) {
      setError(problem);
      return;
    }
    if (task) await updateTask(task.id, values);
    else await addTask({ ...values, title: form.title, goalId: draft?.goalId ?? null, milestoneId: draft?.milestoneId ?? null, projectId: draft?.projectId ?? null });
    onClose();
  };

  return (
    <Dialog
      open={open}
      onClose={onClose}
      title={task ? "Edit task" : "New task"}
      subtitle={task?.origin === "generated" && !task.edited ? "Generated by the Goal Compiler — editing keeps it safe when you revise the plan." : undefined}
      footer={
        <>
          {task && (
            <Button
              variant="danger-ghost"
              icon={<Trash2 size={15} />}
              onClick={async () => {
                await deleteTask(task.id);
                onClose();
              }}
            >
              Delete
            </Button>
          )}
          <span className="spacer" />
          <Button variant="ghost" onClick={onClose}>
            Cancel
          </Button>
          <Button variant="primary" onClick={save} disabled={!form.title.trim()}>
            {task ? "Save" : "Add task"}
          </Button>
        </>
      }
    >
      <form
        onSubmit={(e) => {
          e.preventDefault();
          void save();
        }}
        style={{ display: "flex", flexDirection: "column", gap: 16 }}
      >
        <Field label="Title" error={error}>
          <TextInput value={form.title} onChange={(e) => patch({ title: e.target.value })} placeholder="What needs doing?" maxLength={160} autoFocus />
        </Field>
        <Field label="Notes">
          <TextArea rows={2} value={form.notes} onChange={(e) => patch({ notes: e.target.value })} placeholder="Optional details" maxLength={1000} />
        </Field>
        <div className="field">
          <span className="field__label">Priority</span>
          <Segmented
            label="Priority"
            value={form.priority}
            onChange={(v) => patch({ priority: v })}
            options={[
              { value: 1, label: "Low" },
              { value: 2, label: "Medium" },
              { value: 3, label: "High" },
              { value: 4, label: "Critical" },
            ]}
          />
        </div>
        <div className="field-row" style={{ gridTemplateColumns: "160px 1fr" }}>
          <Field label="Duration">
            <NumberInput value={form.estimateMin} min={5} max={960} suffix="min" onChange={(v) => patch({ estimateMin: v })} />
          </Field>
          <div className="field">
            <span className="field__label">&nbsp;</span>
            <div style={{ display: "flex", gap: 6, flexWrap: "wrap", alignItems: "center", minHeight: 40 }}>
              {QUICK.map((m) => (
                <Button key={m} size="sm" variant={form.estimateMin === m ? "primary" : "ghost"} onClick={() => patch({ estimateMin: m })}>
                  {m < 60 ? `${m}m` : `${m / 60}h`}
                </Button>
              ))}
            </div>
          </div>
        </div>
        <div className="field">
          <span className="field__label">Energy required</span>
          <Segmented
            label="Energy required"
            value={form.energy}
            onChange={(v) => patch({ energy: v })}
            options={[
              { value: "none", label: "Any" },
              { value: "low", label: "Low" },
              { value: "medium", label: "Medium" },
              { value: "high", label: "Deep focus" },
            ]}
          />
        </div>
        <div className="field-row">
          <Field label="Deadline" hint="Optional">
            <DateInput value={form.deadline} onChange={(v) => patch({ deadline: v })} />
          </Field>
          <Field label="Due by" hint={form.deadline ? "Optional time" : "Set a date first"}>
            <TimeInput value={form.deadlineTime} allowEmpty onChange={(v) => patch({ deadlineTime: v })} disabled={!form.deadline} />
          </Field>
        </div>
        <label className="check" style={{ justifyContent: "space-between" }}>
          <span>
            <span style={{ color: "var(--text)", fontWeight: 560 }}>Available to the day planner</span>
            <br />
            <span className="faint" style={{ fontSize: 12 }}>
              Planner tasks appear in the backlog and can be scheduled automatically.
            </span>
          </span>
          <Switch checked={form.inPlanner} onChange={(v) => patch({ inPlanner: v })} label="Available to the day planner" />
        </label>
        <button type="submit" hidden />
      </form>
    </Dialog>
  );
}
