import { ArrowLeft, Cpu, Sparkles, Wand2 } from "lucide-react";
import { useEffect, useState } from "react";
import { aiConfigured, type CompileOutcome } from "../../ai/planProvider";
import { validateGoalText } from "../../domain/goalCompiler";
import { formatDuration, formatShortDate } from "../../domain/time";
import { createBlankGoal, compilePreview, createGoal, navigate, useApp } from "../../state/store";
import { DateInput, NumberInput, TextArea } from "../../ui/fields";
import { Button, Dialog, Field, Switch } from "../../ui/primitives";
import { PriorityDot } from "../../ui/taskBits";

const EXAMPLES = [
  "Become a better backend developer",
  "Prepare for my university exams",
  "Run a half marathon",
  "Launch my side project",
  "Write a short story collection",
];

export function SourceBadge({ source, model }: { source: "template" | "ai" | "manual"; model: string | null }) {
  if (source === "ai") {
    return (
      <span className="badge-source badge-source--ai" title="Generated by an AI model">
        <Sparkles size={12} /> Claude · {model}
      </span>
    );
  }
  if (source === "template") {
    return (
      <span className="badge-source" title="Generated by the deterministic built-in planner, not an AI model">
        <Cpu size={12} /> Built-in planner
      </span>
    );
  }
  return <span className="badge-source">Created manually</span>;
}

export function PlanPreview({ outcome }: { outcome: CompileOutcome }) {
  const { plan } = outcome;
  const total = plan.milestones.reduce((s, m) => s + m.projects.reduce((s2, p) => s2 + p.tasks.reduce((s3, t) => s3 + t.estimateMin, 0), 0), 0);
  const count = plan.milestones.reduce((s, m) => s + m.projects.reduce((s2, p) => s2 + p.tasks.length, 0), 0);
  return (
    <div className="plan-preview">
      <div className="plan-preview__head">
        <SourceBadge source={plan.source} model={plan.model} />
        <span className="faint" style={{ fontSize: 13 }}>
          {plan.milestones.length} milestones · {count} tasks · ≈ {formatDuration(total)}
        </span>
      </div>
      {outcome.fallbackReason && <p className="notice notice--warn">{outcome.fallbackReason}</p>}
      {plan.notes.length > 0 && (
        <ul className="plan-preview__notes">
          {plan.notes.map((n) => (
            <li key={n}>{n}</li>
          ))}
        </ul>
      )}
      <ol className="plan-preview__list">
        {plan.milestones.map((m, i) => (
          <li key={i} className="plan-preview__milestone">
            <div className="plan-preview__mhead">
              <span className="plan-preview__num">{i + 1}</span>
              <strong>{m.title}</strong>
              {m.deadline && <span className="chip">by {formatShortDate(m.deadline)}</span>}
            </div>
            {m.projects.map((p, pi) => (
              <div key={pi} className="plan-preview__project">
                <div className="eyebrow" style={{ marginBottom: 6 }}>{p.title}</div>
                <ul>
                  {p.tasks.map((t, ti) => (
                    <li key={ti}>
                      <PriorityDot priority={t.priority} />
                      <span style={{ flex: 1 }}>{t.title}</span>
                      <span className="faint tabular" style={{ fontSize: 12 }}>
                        {formatDuration(t.estimateMin)}
                      </span>
                    </li>
                  ))}
                </ul>
              </div>
            ))}
          </li>
        ))}
      </ol>
    </div>
  );
}

export function GoalComposer() {
  const open = useApp((s) => s.composerOpen);
  const ai = useApp((s) => s.ai);
  const canUseAi = aiConfigured(ai);
  const [text, setText] = useState("");
  const [description, setDescription] = useState("");
  const [targetDate, setTargetDate] = useState<string | null>(null);
  const [hours, setHours] = useState(5);
  const [useAi, setUseAi] = useState(canUseAi);
  const [busy, setBusy] = useState(false);
  const [outcome, setOutcome] = useState<CompileOutcome | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    if (open) {
      setText("");
      setDescription("");
      setTargetDate(null);
      setHours(5);
      setOutcome(null);
      setError(null);
      setUseAi(canUseAi);
    }
  }, [open, canUseAi]);

  const close = () => useApp.setState({ composerOpen: false });

  const compile = async () => {
    const problem = validateGoalText(text);
    if (problem) {
      setError(problem);
      return;
    }
    setBusy(true);
    setError(null);
    try {
      setOutcome(await compilePreview({ text, targetDate, hoursPerWeek: hours }, useAi && canUseAi, description));
    } catch (e) {
      setError(e instanceof Error ? e.message : String(e));
    } finally {
      setBusy(false);
    }
  };

  return (
    <Dialog
      open={open}
      onClose={close}
      wide
      title={outcome ? "Review your plan" : "What do you want to achieve?"}
      subtitle={outcome ? "Create it as-is — every milestone and task stays editable." : "Describe a goal in your own words. Life OS compiles it into milestones, projects and tasks."}
      footer={
        outcome ? (
          <>
            <Button variant="ghost" icon={<ArrowLeft size={15} />} onClick={() => setOutcome(null)}>
              Back
            </Button>
            <span className="spacer" />
            <Button variant="glass" onClick={compile} disabled={busy}>
              Recompile
            </Button>
            <Button
              variant="primary"
              onClick={async () => {
                setBusy(true);
                await createGoal(outcome.plan, description);
                setBusy(false);
              }}
              disabled={busy}
            >
              Create goal
            </Button>
          </>
        ) : (
          <>
            <Button
              variant="ghost"
              onClick={async () => {
                const problem = validateGoalText(text);
                if (problem) return setError(problem);
                await createBlankGoal(text);
              }}
            >
              Start empty instead
            </Button>
            <span className="spacer" />
            <Button variant="ghost" onClick={close}>
              Cancel
            </Button>
            <Button variant="primary" icon={<Wand2 size={15} />} onClick={compile} disabled={busy || !text.trim()}>
              {busy ? (useAi && canUseAi ? "Asking Claude…" : "Compiling…") : "Compile plan"}
            </Button>
          </>
        )
      }
    >
      {outcome ? (
        <PlanPreview outcome={outcome} />
      ) : (
        <form
          onSubmit={(e) => {
            e.preventDefault();
            void compile();
          }}
          style={{ display: "flex", flexDirection: "column", gap: 18 }}
        >
          <Field label="Goal" error={error}>
            <TextArea
              className="composer__goal"
              rows={2}
              value={text}
              maxLength={240}
              onChange={(e) => setText(e.target.value)}
              placeholder="e.g. Become a better backend developer"
              autoFocus
              onKeyDown={(e) => {
                if (e.key === "Enter" && !e.shiftKey) {
                  e.preventDefault();
                  void compile();
                }
              }}
            />
          </Field>
          <div className="composer__examples" aria-label="Examples">
            {EXAMPLES.map((ex) => (
              <button key={ex} type="button" className="chip composer__example" onClick={() => setText(ex)}>
                {ex}
              </button>
            ))}
          </div>
          <Field label="Context" hint="Optional — what you already know, constraints, what success means.">
            <TextArea rows={2} value={description} maxLength={600} onChange={(e) => setDescription(e.target.value)} />
          </Field>
          <div className="field-row">
            <Field label="Target date" hint="Optional">
              <DateInput value={targetDate} onChange={setTargetDate} />
            </Field>
            <Field label="Time per week" hint="Used to pace deadlines">
              <NumberInput value={hours} min={1} max={80} suffix="hours" onChange={setHours} />
            </Field>
          </div>
          <div className="ai-row">
            <div style={{ flex: 1 }}>
              <div style={{ fontWeight: 560, display: "flex", alignItems: "center", gap: 8 }}>
                <Sparkles size={15} color="var(--violet-300)" /> Use Claude to draft the plan
              </div>
              <div className="faint" style={{ fontSize: 12.5, marginTop: 2 }}>
                {canUseAi ? (
                  <>Sends the goal text to Anthropic using your key ({ai.model}).</>
                ) : (
                  <>
                    No AI provider configured — the built-in planner will be used.{" "}
                    <button
                      type="button"
                      className="link"
                      onClick={() => {
                        close();
                        navigate("settings");
                      }}
                    >
                      Configure in Settings
                    </button>
                  </>
                )}
              </div>
            </div>
            <Switch checked={useAi && canUseAi} disabled={!canUseAi} onChange={setUseAi} label="Use Claude to draft the plan" />
          </div>
          <button type="submit" hidden />
        </form>
      )}
    </Dialog>
  );
}
