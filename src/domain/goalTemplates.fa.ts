// ---- recognising Persian goals -------------------------------------------------

/** Normalises the spellings that vary between keyboards. */
export const normalizeFa = (text: string) => text.replace(/‌/g, "").replace(/ي/g, "ی").replace(/ك/g, "ک");

/** Patterns are written without half-spaces and matched against normalised text. */
export const FA_MATCH: Record<string, RegExp> = {
  exam: /امتحان|کنکور|آزمون|آیلتس|تافل|میانترم|پایانترم|دانشگاه|مدرسه|مدرک/,
  fitness: /ماراتن|بدوم|دویدن|باشگاه|ورزش|وزن|لاغر|چاق|عضله|تناسب اندام|سلامت|خوابم|رژیم|یوگا/,
  career: /شغل|کار پیدا|کار جدید|استخدام|مصاحبه|ترفیع|رزومه|کارآموزی/,
  writing: /بنویسم|نوشتن|کتاب|رمان|وبلاگ|مقاله|پایاننامه|پادکست|آهنگ|نقاشی|فیلم|داستان/,
  build: /بسازم|ساختن|راه بندازم|راهاندازی|لانچ|اپلیکیشن|اپلیکیشن| اپ |سایت|محصول|استارتاپ|کسبوکار|بیزینس|فروشگاه|بازی/,
  skill: /یاد بگیرم|یادگیری|بهتر|حرفهای|مهارت|تمرین|زبان|مسلط|تقویت/,
};

export const FA_TECH = /برنامهنویس|بکاند|فرانت|کدنویسی|توسعهدهنده|دواپس|هوش مصنوعی/;
